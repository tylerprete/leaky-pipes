"""Train the learned evaluation: P(this player wins | position features).
python3 tools/train-value.py /tmp/vd/a.csv /tmp/vd/b.csv   -> tools/results/value-net.js
Splits by game (not by row) so the held-out score is honest."""
import sys, json, numpy as np
from sklearn.linear_model import LogisticRegression
from sklearn.neural_network import MLPClassifier
from sklearn.metrics import log_loss, roc_auc_score

d = np.concatenate([np.loadtxt(f, delimiter=',') for f in sys.argv[1:]])
seed, X, y = d[:, 0], d[:, 1:-1], d[:, -1]
test = ((seed * 7919) % 97) < 10
mu, sd = X[~test].mean(0), X[~test].std(0)
sd[sd < 1e-3] = 0  # constant in training: ignored at play time
Z = (X - mu) / np.where(sd > 0, sd, 1)
print('rows', len(y), 'games', len(np.unique(seed)), 'win share', y.mean().round(3))

def report(name, p):
    print(f'{name:28s} log loss {log_loss(y[test], p):.4f}  AUC {roc_auc_score(y[test], p):.4f}')

n = np.where(X[:, 26] == 1, 2, np.where(X[:, 27] == 1, 3, 4))
report('guess 1/players', (1 / n)[test])
# what the search uses today: my cost and leak against the rival's
old = np.c_[-(X[:, 0]) - 1.0 * X[:, 2] - 0.8 * X[:, 2] * (X[:, 4] == 0) + 0.3 * X[:, 4] + (X[:, 13]) + 1.0 * X[:, 15] + 0.8 * X[:, 15] * (X[:, 17] == 0) - 0.3 * X[:, 17], X[:, 26:29]]
report('today\'s evaluation (refit)', LogisticRegression(max_iter=500).fit(old[~test], y[~test]).predict_proba(old[test])[:, 1])
lr = LogisticRegression(max_iter=1000).fit(Z[~test], y[~test])
report('logistic, all features', lr.predict_proba(Z[test])[:, 1])
mlp = MLPClassifier(hidden_layer_sizes=(32, 16), alpha=1e-4, max_iter=60, early_stopping=True, random_state=0).fit(Z[~test], y[~test])
report('small network (32,16)', mlp.predict_proba(Z[test])[:, 1])
for k in (2, 3, 4):
    m = test & (n == k)
    print(f'  {k}p network log loss {log_loss(y[m], mlp.predict_proba(Z[m])[:, 1]):.4f}  today {log_loss(y[m], LogisticRegression(max_iter=500).fit(old[~test], y[~test]).predict_proba(old[m])[:, 1]):.4f}')

r = lambda a: np.round(a, 4).tolist()
model = {'mu': r(mu), 'sd': r(sd), 'W': [r(w.T) for w in mlp.coefs_], 'b': [r(b) for b in mlp.intercepts_]}
js = "/* Learned evaluation weights. Generated by tools/train-value.py; do not edit. */\n(function (root) {\n  const V = " + json.dumps(model, separators=(',', ':')) + ";\n  if (typeof module !== 'undefined' && module.exports) module.exports = V;\n  else root.LP_VALUE = V;\n})(typeof self !== 'undefined' ? self : this);\n"
open(__file__.rsplit('/', 2)[0] + '/tools/results/value-net.js', 'w').write(js)
print('wrote tools/results/value-net.js', len(js) // 1024, 'KB')
